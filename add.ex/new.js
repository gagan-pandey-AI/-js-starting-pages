// Create a function to calculate the total price
const add = function(a, b) {
    return a + b;
};

// Prices of two products
let mobilePrice = 15000;
let headphonePrice = 2000;

// Calculate the total price
let totalPrice = add(mobilePrice, headphonePrice);

// Display the result
console.log("Mobile Price: ₹" + mobilePrice);
console.log("Headphone Price: ₹" + headphonePrice);
console.log("Total Price: ₹" + totalPrice);